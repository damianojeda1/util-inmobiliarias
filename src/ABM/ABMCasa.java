    private boolean extraerCasa(){
        ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT id_casa, edificado_casa, banos_casa, ambientes_casa, dormitorios_casa, \n" +
        "       patio_casa, garaje_casa, asador_casa, nropisos_casa, pileta_casa, \n" +
        "       quincho_casa, id_inmueble_casa, observacion_inmueble\n" +
        " FROM inmobiliaria.casa INNER JOIN inmobiliaria.inmueble on id_inmueble = id_inmueble_casa WHERE id_inmueble_casa="+this.inm.getId()+";");
        try {
            if (rs.next()){
                if (!rs.getString("observacion_inmueble").isEmpty()){
                    String [] obs = rs.getString("observacion_inmueble").split("Casa: ");
                    if (obs.length>1)
                        taObs.setText(obs[1].split("-")[0]);
                }
                this.tfEdificado.setText(String.valueOf(rs.getInt("edificado_casa")));
                this.tfAmbientes.setText(rs.getString("ambientes_casa"));
                this.tfDorm.setText(rs.getString("dormitorios_casa"));
                this.tfBano.setText(rs.getString("banos_casa"));
                this.tfGaraje.setText(rs.getString("garaje_casa"));
                this.tfPisos.setText(rs.getString("nropisos_casa"));
                if (rs.getBoolean("asador_casa"))
                    this.rbtnAsaS.setSelected(true);
                else
                    this.rbtnAsaN.setSelected(true);
                if (rs.getBoolean("patio_casa"))
                    this.rbtnPatioS.setSelected(true);
                else
                    this.rbtnPatioN.setSelected(true);
                if (rs.getBoolean("pileta_casa"))
                    this.rbtnPileS.setSelected(true);
                else
                    this.rbtnPileN.setSelected(true);
                if (rs.getBoolean("quincho_casa"))
                    this.rbtnQuinS.setSelected(true);
                else
                    this.rbtnQuinN.setSelected(true);

                return true;
            }else 
                return false;
        } catch (Exception e) {
            Datos.Procedimientos.escribirEnLog("Error en linea 454 metodo extraerCasa() en la clase ABMCasa.java: "+e);
            return false;
        }
    }
    public void mostrar(Objetos.Inmueble inm, boolean editando){
        setVisible(true);
        this.inm = inm;
        this.editando = editando;
        if (editando) {
            if (!extraerCasa())
                editando = false;
        } else {
            limpiar();
        }
    }
    
