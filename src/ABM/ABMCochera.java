    private void continuar(){
        this.inm.setObservacion("Cochera: "+this.taObs.getText()+"-");
        if (this.inm.getId()==-1){
            this.inm.insertarInmueble();
        } else {
            inm.actualizarDB();
        }  
        try {
            ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT 'Cochera' FROM inmobiliaria.cochera WHERE id_inmueble_cochera = "+inm.getId());
            boolean actualizar = editando && rs.next();
            if (actualizar){
                ProcedimientosSQL.SqlMetodo.runQuery("UPDATE inmobiliaria.cochera\n" +
                                                "SET  capacidad_cochera="+tfCapacidad.getText()+", capacidadtechada_cochera="+tfCapacidadT.getText()+", \n" +
                                                "bano_cochera="+tfBanos.getText()+", oficina_cochera="+tfOficinas.getText()+", nropisos_cochera="+this.tfPisos.getText()+"\n" +
                                                " WHERE id_inmueble_cochera = "+inm.getId()+" ;");
            } else {
                ProcedimientosSQL.SqlMetodo.runQuery("INSERT INTO inmobiliaria.cochera(\n" +
                "            capacidad_cochera, capacidadtechada_cochera, bano_cochera, \n" +
                "            oficina_cochera, nropisos_cochera, id_inmueble_cochera)\n" +
                "    VALUES ("+this.tfCapacidad.getText()+", "+this.tfCapacidadT.getText()+", "+this.tfBanos.getText()+", \n" +
                "            "+this.tfOficinas.getText()+", "+this.tfPisos.getText()+", "+this.inm.getId()+");");
            } 
        } catch (Exception ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 328 metodo continuar() en la clase ABMCochera.java: "+ex);
        }
        Datos.Instancias.getInstance().pantallaPrincipal.refrezcarListas("Inmueble");
        this.limpiar();
        this.dispose();
    }  
    private boolean extraerCochera(){
        ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT id_cochera, capacidad_cochera, capacidadtechada_cochera, bano_cochera, \n" +
                                                            "oficina_cochera, nropisos_cochera, observacion_inmueble\n" +
                                                            " FROM inmobiliaria.cochera INNER JOIN inmobiliaria.inmueble on id_inmueble = id_inmueble_cochera WHERE id_inmueble_cochera="+this.inm.getId()+";");
        try {
            if (rs.next()){
                if (!rs.getString("observacion_inmueble").isEmpty()){
                    String [] obs = rs.getString("observacion_inmueble").split("Cochera: ");
                    if (obs.length>1)
                        taObs.setText(obs[1].split("-")[0]);
                }
                tfCapacidad.setText(String.valueOf(rs.getInt("capacidad_cochera")));
                tfCapacidadT.setText(String.valueOf(rs.getInt("capacidadtechada_cochera")));
                tfBanos.setText(String.valueOf(rs.getInt("bano_cochera")));
                tfOficinas.setText(String.valueOf(rs.getInt("oficina_cochera")));
                tfPisos.setText(String.valueOf(rs.getInt("nropisos_cochera")));

                return true;
            }else 
                return false;
        } catch (Exception e) {
            Datos.Procedimientos.escribirEnLog("Error en linea 355 metodo extraerCosecha() en la clase ABMCosecha.java: "+e);
            return false;
        }
    }
    public void mostrar(Objetos.Inmueble inm, boolean editando){
        setVisible(true);
        this.inm = inm;
        this.editando = editando;
        if (editando) {
            if (!extraerCochera())
                editando = false;
        } else {
            limpiar();
        }
    }
    
    private void limpiar(){
        this.tfBanos.setText("");
        this.tfCapacidad.setText("");
        this.tfCapacidadT.setText("");
        this.tfOficinas.setText("");
        this.tfPisos.setText("");
        this.taObs.setText("");
    }
