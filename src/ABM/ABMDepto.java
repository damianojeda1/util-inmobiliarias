    private boolean extraerDepto(){
        ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT id_departamento, edificado_departamento, expensa_departamento, \n" +
                                        "banos_departamento, ambiente_departamento, balcon_departamento, \n" +
                                        "dormitorio_departamento, asador_departamento, piso_departamento, \n" +
                                        "cochera_departamento, observacion_inmueble, dpto_departamento\n" +
                                        "FROM inmobiliaria.departamento INNER JOIN inmobiliaria.inmueble on id_inmueble = id_inmueble_departamento WHERE id_inmueble_departamento="+this.inm.getId()+";");
        try {
            if (rs.next()){
                
                if (!rs.getString("observacion_inmueble").isEmpty()){
                    String [] obs = rs.getString("observacion_inmueble").split("Departamento: ");
                    if (obs.length>1)
                        taObs.setText(obs[1].split("-")[0]);
                }
                tfEdificado.setText(String.valueOf(rs.getInt("edificado_departamento")));
                tfExpensas.setText(String.valueOf(rs.getInt("expensa_departamento")));
                tfAmbientes.setText(rs.getString("ambiente_departamento"));
                tfDorm.setText(rs.getString("dormitorio_departamento"));
                tfBano.setText(rs.getString("banos_departamento"));
                cbPiso.setSelectedIndex(rs.getInt("piso_departamento"));
                tfDpto.setText(rs.getString("dpto_departamento"));
                if (rs.getBoolean("asador_departamento"))
                    this.rbtnAsadorS.setSelected(true);
                else
                    this.rbtnAsadorN.setSelected(true);
                if (rs.getBoolean("balcon_departamento"))
                    this.rbtnBalconS.setSelected(true);
                else
                    this.rbtnBalconN.setSelected(true);
                if (rs.getBoolean("cochera_departamento"))
                    this.rbtnCocheraS.setSelected(true);
                else
                    this.rbtnCocheraN.setSelected(true);

                return true;
            }else 
                return false;
        } catch (Exception e) {
            Datos.Procedimientos.escribirEnLog("Error en linea 511 metodo extraerDepto en la clase ABMDepto.java: "+e);
            return false;
        }
    }
    
    public void mostrar(Objetos.Inmueble inm, boolean editando){
        setVisible(true);
        this.inm = inm;
        this.editando = editando;
        if (editando) {
            if (!extraerDepto())
                editando = false;
        } 
        else {
            limpiar();
        }
    }
    
    private void limpiar(){
        this.tfAmbientes.setText("");
        this.tfBano.setText("");
        this.tfDorm.setText("");
        this.tfEdificado.setText("");
        this.tfExpensas.setText("");
        this.cbPiso.setSelectedIndex(0);
        this.taObs.setText("");
        tfDpto.setText("");
    }
