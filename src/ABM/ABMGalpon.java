    private boolean controlesOK(){
        if (!Datos.Procedimientos.isNumber(this.tfEdificado.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese un valor válido para edificado");
            this.tfEdificado.grabFocus();
            return false;
        }else{
            if (this.tfEdificado.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "Edificado debe ser un número entero");
                this.tfEdificado.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfEdificado.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "Edificado debe ser un número mayor a 0");
                    this.tfEdificado.grabFocus();
                    return false;
                }
            }
        }
        
        if (!Datos.Procedimientos.isNumber(this.tfCapacidad.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese un valor válido para la capacidad");
            this.tfCapacidad.grabFocus();
            return false;
        }else{
            if (this.tfCapacidad.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "La capacidad debe ser un número entero");
                this.tfCapacidad.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfCapacidad.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "La capacidad debe ser un número mayor a 0");
                    this.tfCapacidad.grabFocus();
                    return false;
                }
            }
        }
        if (!Datos.Procedimientos.isNumber(this.tfOficinas.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida para las oficinas");
            this.tfOficinas.grabFocus();
            return false;
        }else{
            if (this.tfOficinas.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "El número de oficinas debe ser un numero entero");
                this.tfOficinas.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfOficinas.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "El número de oficinas debe ser mayor a cero");
                    this.tfOficinas.grabFocus();
                    return false;
                }
            }
        }
        if (!Datos.Procedimientos.isNumber(this.tfBanos.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida para los baños");
            this.tfBanos.grabFocus();
            return false;
        }else{
            if (this.tfBanos.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "El número de baños debe ser un numero entero");
                this.tfBanos.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfBanos.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "El número de baños debe ser mayor a cero");
                    this.tfBanos.grabFocus();
                    return false;
                }
            }
        }   
        return true;
    }
    
    private void continuar(){
        this.inm.setObservacion("Galpon: "+taObs.getText()+"-");
        if (this.inm.getId()==-1){
            this.inm.insertarInmueble();
        } else {
            inm.actualizarDB();
        }        
        try {
            ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT 'Galpon' FROM inmobiliaria.galpon WHERE id_inmueble_galpon = "+inm.getId());
            boolean actualizar = editando && rs.next();
            if (actualizar){         
                ProcedimientosSQL.SqlMetodo.runQuery("UPDATE inmobiliaria.galpon\n" +
                    "SET  edificado_galpon="+tfEdificado.getText()+", capacidad_galpon="+tfCapacidad.getText()+", \n" +
                    "bano_galpon="+tfBanos.getText()+", oficina_galpon="+tfOficinas.getText()+"\n" +
                    " WHERE id_inmueble_galpon = "+inm.getId()+" ;");
            } else {
                ProcedimientosSQL.SqlMetodo.runQuery("INSERT INTO inmobiliaria.galpon(\n" +
                    "            edificado_galpon, capacidad_galpon, bano_galpon, \n" +
                    "            oficina_galpon,  id_inmueble_galpon)\n" +
                    "    VALUES ("+this.tfEdificado.getText()+", "+this.tfCapacidad.getText()+", "+this.tfBanos.getText()+", \n" +
                    "            "+this.tfOficinas.getText()+", "+this.inm.getId()+");");
            }    
        } catch (Exception ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 303 metodo continuar en la clase ABMGalpon.java: "+ex);
        }
        
        Datos.Instancias.getInstance().pantallaPrincipal.refrezcarListas("Inmueble");
        this.limpiar();
        this.dispose();
    }  
    private boolean extraerGalpon(){
        ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT id_galpon, capacidad_galpon, edificado_galpon, bano_galpon, \n" +
                                                            "oficina_galpon, observacion_inmueble\n" +
                                                            "FROM inmobiliaria.galpon "
                + "INNER JOIN inmobiliaria.inmueble on id_inmueble = id_inmueble_galpon WHERE id_inmueble_galpon="+this.inm.getId()+";");
        try {
            if (rs.next()){
                tfEdificado.setText(String.valueOf(rs.getInt("edificado_galpon")));
                tfCapacidad.setText(String.valueOf(rs.getInt("capacidad_galpon")));
                tfBanos.setText(String.valueOf(rs.getInt("bano_galpon")));
                tfOficinas.setText(String.valueOf(rs.getInt("oficina_galpon")));
                if (!rs.getString("observacion_inmueble").isEmpty()){
                    String [] galpon = rs.getString("observacion_inmueble").split("Galpon: ");
                    if (galpon.length>1)
                        taObs.setText(galpon[1].split("-")[0]);
                }
                return true;
            }else 
                return false;
        } catch (Exception e) {
            Datos.Procedimientos.escribirEnLog("Error en linea 330 metodo extraergalpon en la clase ABMGalpon.java: "+e);
            return false;
        }
    }
    public void mostrar(Objetos.Inmueble inm, boolean editando){
        setVisible(true);
        this.inm = inm;
        this.editando = editando;
        if (editando) {
            if (!extraerGalpon())
                editando = false;
        } else {
            limpiar();
        }
    }
    
    private void limpiar(){
        this.tfBanos.setText("");
        this.tfEdificado.setText("");
        this.tfCapacidad.setText("");
        this.tfOficinas.setText("");
        this.taObs.setText("");
    }
