    private boolean extraerLocal(){
        ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT id_local, expensa_local, cochera_local, estacionamiento_local, \n" +
                                                            "bano_local, cocina_local, calefaccion_local, edificado_local, \n" +
                                                            "ambiente_local, aire_local, observacion_inmueble\n" +
                                                            "FROM inmobiliaria.local INNER JOIN inmobiliaria.inmueble on id_inmueble = id_inmueble_local WHERE id_inmueble_local="+inm.getId()+";");
        try {
            if (rs.next()){
                if (!rs.getString("observacion_inmueble").isEmpty()){
                    String [] obs = rs.getString("observacion_inmueble").split("Local: ");
                    if (obs.length>1)
                        taObs.setText(obs[1].split("-")[0]);
                }
                tfEdificado.setText(String.valueOf(rs.getInt("edificado_local")));
                tfAmbientes.setText(rs.getString("ambiente_local"));
                tfExpensas.setText(rs.getString("expensa_local"));
                tfBanos.setText(rs.getString("bano_local"));
                tfCapacidadC.setText(rs.getString("cochera_local"));
                cbCalef.setSelectedItem(rs.getString("calefaccion_local"));
                if (rs.getBoolean("estacionamiento_local"))
                    rbtnEstS.setSelected(true);
                else
                    rbtnEstN.setSelected(true);
                if (rs.getBoolean("cocina_local"))
                    rbtnCocinaS.setSelected(true);
                else
                    rbtnCocinaN.setSelected(true);
                if (rs.getBoolean("aire_local"))
                    rbtnAireS.setSelected(true);
                else
                    rbtnAireN.setSelected(true);
               

                return true;
            }else 
                return false;
        } catch (Exception e) {
            Datos.Procedimientos.escribirEnLog("Error en linea 514 metodo extraerLocal en la clase ABMLocal.java: "+e);
            return false;
        }
    }
    
    public void mostrar(Objetos.Inmueble inm, boolean editando){
        setVisible(true);
        this.inm = inm;
        this.editando = editando;
        if (editando) {
            if (!extraerLocal())
                editando = false;
        } else {
            limpiar();
        }
    }
    
    private void limpiar(){
        this.tfAmbientes.setText("");
        this.tfBanos.setText("");
        this.tfCapacidadC.setText("");
        this.tfEdificado.setText("");
        this.tfExpensas.setText("");
        this.taObs.setText("");
    }
