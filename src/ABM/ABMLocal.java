    private boolean controlesOK(){
        if (!Datos.Procedimientos.isNumber(this.tfEdificado.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese un valor válido de m2 edificados");
            this.tfEdificado.grabFocus();
            return false;
        }else{
            if (this.tfEdificado.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "Los metros cuadrados edificados deben ser un número entero");
                this.tfEdificado.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfEdificado.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "Los metros cuadrados edificados deben ser mayores a 0");
                    this.tfEdificado.grabFocus();
                    return false;
                }
            }
        } 
        
        if (!Datos.Procedimientos.isNumber(this.tfAmbientes.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida para los ambientes");
            this.tfAmbientes.grabFocus();
            return false;
        }else{
            if (this.tfAmbientes.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "El número de ambientes debe ser un numero entero");
                this.tfAmbientes.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfAmbientes.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "El número de ambientes debe ser mayor a cero");
                    this.tfAmbientes.grabFocus();
                    return false;
                }
            }
        }
        
        if (!Datos.Procedimientos.isNumber(this.tfExpensas.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese un valor válido de expensas");
            this.tfExpensas.grabFocus();
            return false;
        }else{
            if (Float.parseFloat(this.tfExpensas.getText()) < 0){
                JOptionPane.showMessageDialog(this, "Las expensas deben ser un valor positivo");
                this.tfExpensas.grabFocus();
                return false;
            }
        }   
        
        if (!Datos.Procedimientos.isNumber(this.tfBanos.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida para los baños");
            this.tfBanos.grabFocus();
            return false;
        }else{
            if (this.tfBanos.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "El número de baños debe ser un numero entero");
                this.tfBanos.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfBanos.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "El número de baños debe ser mayor a cero");
                    this.tfBanos.grabFocus();
                    return false;
                }
            }
        }  
        
        if (!Datos.Procedimientos.isNumber(this.tfCapacidadC.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida para la capacidad de la cochera");
            this.tfCapacidadC.grabFocus();
            return false;
        }else{
            if (this.tfCapacidadC.getText().contains(".")){
                JOptionPane.showMessageDialog(this, "La capacidad de la cochera debe ser un numero entero");
                this.tfCapacidadC.grabFocus();
                return false;
            }else{
                if (Integer.parseInt(this.tfCapacidadC.getText()) < 0){
                    JOptionPane.showMessageDialog(this, "La capacidad de la cochera debe ser mayor a cero");
                    this.tfCapacidadC.grabFocus();
                    return false;
                }
            }
        }

        return true;
    }
    
    private void continuar(){
        this.inm.setObservacion("Local: "+this.taObs.getText()+"-");
        if (this.inm.getId()==-1){
            this.inm.insertarInmueble();
        } else {
            inm.actualizarDB();
        }  
        try {
            ResultSet rs = ProcedimientosSQL.SqlMetodo.runQuery("SELECT 'Local' FROM inmobiliaria.local WHERE id_inmueble_local = "+inm.getId());
            boolean actualizar = editando && rs.next();
            if (actualizar){
                ProcedimientosSQL.SqlMetodo.runQuery("UPDATE inmobiliaria.local\n" +
                    "SET  expensa_local="+tfExpensas.getText()+", cochera_local="+tfCapacidadC.getText()+", estacionamiento_local="+rbtnEstS.isSelected()+", \n" +
                    "bano_local="+tfBanos.getText()+", cocina_local="+rbtnCocinaS.isSelected()+", calefaccion_local='"+cbCalef.getSelectedItem()+"', edificado_local="+tfEdificado.getText()+", \n" +
                    "ambiente_local="+tfAmbientes.getText()+", aire_local="+rbtnAireS.isSelected()+"\n" +
                    " WHERE id_inmueble_local= "+inm.getId()+" ;");
            } else {
                ProcedimientosSQL.SqlMetodo.runQuery("INSERT INTO inmobiliaria.local(\n" +
                "            expensa_local, cochera_local, estacionamiento_local, \n" +
                "            bano_local, cocina_local, calefaccion_local, edificado_local, \n" +
                "            ambiente_local, aire_local, id_inmueble_local)\n" +
                "    VALUES ("+this.tfExpensas.getText()+", "+this.tfCapacidadC.getText()+", "+this.rbtnEstS.isSelected()+", \n" +
                "            "+this.tfBanos.getText()+", "+this.rbtnCocinaS.isSelected()+", '"+this.cbCalef.getSelectedItem()+"', "+this.tfEdificado.getText()+", \n" +
                "            "+this.tfAmbientes.getText()+", "+this.rbtnAireS.isSelected()+", "+this.inm.getId()+");");
            }
        } catch (Exception ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 471 metodo continuar en la clase ABMLocal.java: "+ex);
        }
        Datos.Instancias.getInstance().pantallaPrincipal.refrezcarListas("Inmueble");
        this.limpiar();
        this.dispose();
    }        
