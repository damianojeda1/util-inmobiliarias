    public boolean esTitular(){
        boolean esTitular = false;
        String query = "Select tipo_persona FROM inmobiliaria.persona WHERE \n"
                + "id_persona = "+Datos.Macros.getID_PERSONA()+"";
        ResultSet rs =SqlMetodo.runQuery(query);
        try {
            while(rs.next()){
                if (rs.getString("tipo_persona").equals("Titular") || rs.getString("tipo_persona").equals("Administrador") ){
                    esTitular = true;
                }
            }
        }catch(SQLException ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 406 metodo esTitular en la clase AbmPersonal.java: "+ex);
        }
        return esTitular;
    };
    
    
    private void btnPersonal1MousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnPersonal1MousePressed
        // TODO add your handling code here:
        if (esTitular()){
            if (Datos.Instancias.getInstance().abmPersonal == null)
            Datos.Instancias.getInstance().abmPersonal = new ABMUsuarios.AbmPersonal();
            Datos.Instancias.getInstance().abmPersonal.mostrar();
        }else{
            JOptionPane.showMessageDialog(this, "No tienes los permisos necesarios para realizar esta operación");
        }
    }//GEN-LAST:event_btnPersonal1MousePressed

    
