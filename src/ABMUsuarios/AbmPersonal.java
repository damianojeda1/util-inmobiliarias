    public boolean esTitular(){
        boolean esTitular = false;
        String query = "Select tipo_persona FROM inmobiliaria.persona WHERE \n"
                + "id_persona = "+Datos.Macros.getID_PERSONA()+"";
        ResultSet rs =SqlMetodo.runQuery(query);
        try {
            while(rs.next()){
                if (rs.getString("tipo_persona").equals("Titular") || rs.getString("tipo_persona").equals("Administrador") ){
                    esTitular = true;
                }
            }
        }catch(SQLException ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 406 metodo esTitular en la clase AbmPersonal.java: "+ex);
        }
        return esTitular;
    };
    
