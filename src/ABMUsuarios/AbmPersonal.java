    private void borrar(){
        int row=tblPersonal.getSelectedRow();
        if(row >= 0){
            DefaultTableModel modelo = (DefaultTableModel) tblPersonal.getModel();
            Integer idPers = (Integer) ((Tripla)modelo.getValueAt(row, 0)).getPrimero();
            if (!((Tripla)modelo.getValueAt(row, 0)).getSegundo().toString().equals("Titular")){
                String query="DELETE FROM inmobiliaria.persona WHERE id_persona ="+idPers;
                SqlMetodo.runQuery(query);
                limpiar();
                llenarTabla();
            }    
        }
    }
    
