    private void guardar(){
        if (controlesOk()){
            ProcedimientosSQL.SqlMetodo.runQuery("UPDATE inmobiliaria.usuario\n" +
            "   SET nombre_usuario='"+tfUsuario.getText()+"', clave_usuario='"+pfNueva1.getText()+"'\n" +
            " WHERE id_usuario="+Macros.getID_USUARIO()+";");
            JOptionPane.showMessageDialog(this, "Usuario Modificado '"+tfUsuario.getText()+"'");
            this.dispose();
        }
    }
    
    private boolean controlesOk(){
        if (this.tfUsuario.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese un nombre de usuario");
            this.tfUsuario.grabFocus();
            return false;            
        }
        if (this.pfAnterior.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese su contraseña actual");
            this.pfAnterior.grabFocus();
            return false;            
        }
        if (this.pfNueva1.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese una contraseña nueva");
            this.pfNueva1.grabFocus();
            return false;            
        }
        
        if (!this.pfAnterior.getText().equals(pass)){
            JOptionPane.showMessageDialog(this, "La contraseña actual no es correcta");
            this.pfAnterior.grabFocus();
            return false;
        }
        if (!this.pfNueva1.getText().equals(this.pfNueva2.getText())){
            JOptionPane.showMessageDialog(this, "La contraseñas nuevas no coinciden");
            this.pfNueva1.grabFocus();
            return false;
        } 
        
        return true;
    }
    
    public void mostrar(){
        ResultSet rs = SqlMetodo.runQuery("SELECT nombre_usuario, clave_usuario FROM inmobiliaria.usuario WHERE id_usuario="+Macros.getID_USUARIO());
        try {
            if (rs.next()){
                tfUsuario.setText(rs.getString("nombre_usuario"));
                pass = rs.getString("clave_usuario");
                this.setVisible(true);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error en base de datos, No se puede cambiar el usuario");
            Datos.Procedimientos.escribirEnLog("Error en linea 240 en mostrar de cambiarUsuarioPropio: "+ex.toString());
        }         
    }
       
