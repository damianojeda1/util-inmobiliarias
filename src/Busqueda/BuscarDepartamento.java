    private  void armarCondicion(){
        if (this.chkLuz.isSelected())
            condicion += " AND luz_inmueble ";        
        if (this.chkAgua.isSelected())
            condicion += " AND agua_inmueble ";
        if (this.chkGas.isSelected())
            condicion += " AND gas_inmueble ";
        if (this.chkCloaca.isSelected())
            condicion += " AND cloaca_inmueble ";
        if (this.chkTelefono.isSelected())
            condicion += " AND telefono_inmueble ";
        if (this.chkPavimento.isSelected())
            condicion += " AND pavimento_inmueble ";
        
        if (this.cbSector.getSelectedIndex() > 0)
            condicion += " AND id_sector_inmueble="+((Objetos.Tripla) this.cbSector.getSelectedItem()).getPrimero()+" ";
        
        if ((Integer)this.spAmbientes.getValue()>0)
            condicion += " AND ambiente_departamento="+this.spAmbientes.getValue()+" ";
        if ((Integer)this.spDormitorios.getValue()>0)
            condicion += " AND dormitorio_departamento="+this.spDormitorios.getValue()+" ";
        if ((Integer)this.spBanos.getValue()>0)
            condicion += " AND banos_departamento="+this.spBanos.getValue()+" ";
            
        if (this.chkBalcon.isSelected()){
            condicion += " AND balcon_departamento "; 
        }else{
            condicion += " AND NOT balcon_departamento ";
        }
           
        if (this.chkAsador.isSelected()){
            condicion += " AND asador_departamento ";
        }else{
            condicion += " AND NOT asador_departamento ";            
        }

        if (this.chkCochera.isSelected()){
            condicion += " AND cochera_departamento ";
        }else{
            condicion += " AND NOT cochera_departamento ";           
        }
    
        if (this.rbtnIgual.isSelected())
            condicion += " AND  piso_departamento="+this.spPiso.getValue()+" ";
        if (this.rbtnMenor.isSelected())
            condicion += " AND  piso_departamento<="+this.spPiso.getValue()+" ";
        if (this.rbtnMayor.isSelected())
            condicion += " AND  piso_departamento>="+this.spPiso.getValue()+" ";
        
      
    }
    
    private void llenarCBSector(){
        cbSector.removeAllItems();
        String consulta = "SELECT id_sector,nombre_sector FROM inmobiliaria.sector;";
        ResultSet rs = SqlMetodo.runQuery(consulta);
        try {
            cbSector.addItem(new Objetos.Tripla(0, null , "Indiferente"));
            while (rs.next())
                cbSector.addItem(new Objetos.Tripla(rs.getObject(1), null , rs.getObject(2)));
        } catch (SQLException ex) {
            Datos.Procedimientos.escribirEnLog(ex.toString());
        }            
    }       
    
    public String obtenerCondicion(){
        return condicion;
    }
