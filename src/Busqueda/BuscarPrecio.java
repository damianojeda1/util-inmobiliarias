    private void btnBuscarMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarMousePressed
        // TODO add your handling code here:
        if (Datos.Procedimientos.isNumber(this.tfValor.getText())){
            armarCondicion();
            this.dispose();
        }
    }//GEN-LAST:event_btnBuscarMousePressed
    
    private  void armarCondicion(){
        if (this.tipo.equals("Alquiler")){
            condicion += " AND valoralquiler_inmueble <"+this.tfValor.getText();
        } else {
            condicion += " AND valorventa_inmueble <"+this.tfValor.getText();
        }
    }     
    
    public String obtenerCondicion(){
        return condicion;
    }
