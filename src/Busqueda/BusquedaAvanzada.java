    private  void armarCondicion(){            
        
        condicion += ((Objetos.Tripla) this.cbLuz.getSelectedItem()).getPrimero();
        condicion += ((Objetos.Tripla) this.cbAgua.getSelectedItem()).getPrimero();
        condicion += ((Objetos.Tripla) this.cbTelefonia.getSelectedItem()).getPrimero();
        condicion += ((Objetos.Tripla) this.cbPavimento.getSelectedItem()).getPrimero();
        condicion += ((Objetos.Tripla) this.cbCloaca.getSelectedItem()).getPrimero();
        condicion += ((Objetos.Tripla) this.cbGas.getSelectedItem()).getPrimero();
        
        if (this.cbSector.getSelectedIndex() > 0)
                condicion += " AND id_sector_inmueble="+((Objetos.Tripla) this.cbSector.getSelectedItem()).getPrimero()+" ";
        
        if (((Objetos.Tripla) this.cbEstado.getSelectedItem()).getTercero().equals("Alquiler")){
            if (this.rbtnIgualP.isSelected())
                condicion += " AND valoralquiler_inmueble = "+this.tfPrecio.getText()+" ";
            if (this.rbtnMenorP.isSelected())
                condicion += " AND  valoralquiler_inmueble <= "+this.tfPrecio.getText()+" ";
            if (this.rbtnMayorP.isSelected())
                condicion += " AND  valoralquiler_inmueble >= "+this.tfPrecio.getText()+" ";
        } else if (((Objetos.Tripla) this.cbEstado.getSelectedItem()).getTercero().equals("Venta")){
            if (this.rbtnIgualP.isSelected())
                condicion += " AND valorventa_inmueble = "+this.tfPrecio.getText()+" ";
            if (this.rbtnMenorP.isSelected())
                condicion += " AND  valorventa_inmueble <= "+this.tfPrecio.getText()+" ";
            if (this.rbtnMayorP.isSelected())
                condicion += " AND  valorventa_inmueble >= "+this.tfPrecio.getText()+" ";
        }
                        
        if (tabbInmueble.getSelectedIndex() == 0){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.campo ON id_inmueble = id_inmueble_campo ";
            condicion += ((Objetos.Tripla) this.cbTipoCampo.getSelectedItem()).getPrimero();
            if ((Integer)this.spGalponCamp.getValue()>0)
                condicion += " AND galpon_campo="+this.spGalponCamp.getValue()+" ";
            if ((Integer)this.spSiloCamp.getValue()>0)
                condicion += " AND silo_campo="+this.spSiloCamp.getValue()+" ";
            if ((Integer)this.spCorralCamp.getValue()>0)
                condicion += " AND corral_campo="+this.spCorralCamp.getValue()+" ";
            if ((Integer)this.spBreteCamp.getValue()>0)
                condicion += " AND brete_campo="+this.spBreteCamp.getValue()+" ";         
            if (this.chkAlambradoCamp.isSelected()){
                condicion += " AND alambrado_campo ";  
            }
        }
        
        if (tabbInmueble.getSelectedIndex() == 1){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.casa ON id_inmueble = id_inmueble_casa ";
            if ((Integer)this.spAmbientesCasa.getValue()>0)
                condicion += " AND ambientes_casa="+this.spAmbientesCasa.getValue()+" ";
            if ((Integer)this.spDormitoriosCasa.getValue()>0)
                condicion += " AND dormitorios_casa="+this.spDormitoriosCasa.getValue()+" ";
            if ((Integer)this.spBanosCasa.getValue()>0)
                condicion += " AND banos_casa="+this.spBanosCasa.getValue()+" ";
            if ((Integer)this.spGarajeCasa.getValue()>0)
                condicion += " AND garaje_casa="+this.spGarajeCasa.getValue()+" ";
            if ((Integer)this.spPisosCasa.getValue()>0)
                condicion += " AND nropisos_casa="+this.spPisosCasa.getValue()+" ";        
            if (this.chkPiletaCasa.isSelected()){
                condicion += " AND pileta_casa ";
            }
            if (this.chkAsadorCasa.isSelected()){
                condicion += " AND asador_casa ";
            }
            if (this.chkPatioCasa.isSelected()){
                condicion += " AND patio_casa ";
            }
            if (this.chkQuinchoCasa.isSelected()){
                condicion += " AND quincho_casa ";
            }    
        }
        
        if (tabbInmueble.getSelectedIndex() == 2){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.cochera ON id_inmueble = id_inmueble_cochera ";            
            if ((Integer)this.spOficinasCoch.getValue()>0)
                condicion += " AND oficina_cochera="+this.spOficinasCoch.getValue()+" ";
            if ((Integer)this.spBanosCoch.getValue()>0)
                condicion += " AND bano_cochera="+this.spBanosCoch.getValue()+" ";          
            }

        if (tabbInmueble.getSelectedIndex() == 3){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.departamento ON id_inmueble = id_inmueble_departamento ";            
            if ((Integer)this.spAmbientesDept.getValue()>0)
                condicion += " AND ambiente_departamento="+this.spAmbientesDept.getValue()+" ";
            if ((Integer)this.spDormitoriosDept.getValue()>0)
                condicion += " AND dormitorio_departamento="+this.spDormitoriosDept.getValue()+" ";
            if ((Integer)this.spBanosDept.getValue()>0)
                condicion += " AND banos_departamento="+this.spBanosDept.getValue()+" ";

            if (this.chkBalconDept.isSelected()){
                condicion += " AND balcon_departamento "; 
            }

            if (this.chkAsadorDept.isSelected()){
                condicion += " AND asador_departamento ";
            }

            if (this.chkCocheraDept.isSelected()){
                condicion += " AND cochera_departamento ";
            }

            if (this.rbtnIgual.isSelected())
                condicion += " AND  piso_departamento="+this.spPisoDept.getValue()+" ";
            if (this.rbtnMenor.isSelected())
                condicion += " AND  piso_departamento<="+this.spPisoDept.getValue()+" ";
            if (this.rbtnMayor.isSelected())
                condicion += " AND  piso_departamento>="+this.spPisoDept.getValue()+" ";
        }
        
        if (tabbInmueble.getSelectedIndex() == 4){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.galpon ON id_inmueble = id_inmueble_galpon ";
            if ((Integer)this.spOficinasGalp.getValue()>0)
                condicion += " AND oficina_galpon="+this.spOficinasGalp.getValue()+" ";
            if ((Integer)this.spBanosGalp.getValue()>0)
                condicion += " AND bano_galpon="+this.spBanosGalp.getValue()+" ";   
        }
        
        if (tabbInmueble.getSelectedIndex() == 5){
            this.tablasInmueble = " inmobiliaria.inmueble INNER JOIN inmobiliaria.local ON id_inmueble = id_inmueble_local ";            
            if ((Integer)this.spAmbientesLocal.getValue()>0)
                condicion += " AND ambiente_local="+this.spAmbientesLocal.getValue()+" ";
            if ((Integer)this.spBanosLocal.getValue()>0)
                condicion += " AND bano_local="+this.spBanosLocal.getValue()+" ";
            if ((Integer)this.spCocheraLocal.getValue()>0)
                condicion += " AND cochera_local="+this.spCocheraLocal.getValue()+" ";

            if (this.chkEstaLocal.isSelected()){
                condicion += " AND estacionamiento_local ";
            }
            if (this.chkCocinaLocal.isSelected()){
                condicion += " AND cocina_local ";
            }     
            if (this.chkAireLocal.isSelected()){
                condicion += " AND aire_local ";
            }
        }

    }
    
    private void llenarCBGenerales(){
        cbLuz.removeAllItems();
        cbLuz.addItem(new Tripla ("", null, "Indiferente"));           
        cbLuz.addItem(new Tripla (" AND luz_inmueble ", null, "Si"));   
        cbLuz.addItem(new Tripla (" AND NOT luz_inmueble ", null, "No"));   
        
        cbAgua.removeAllItems();
        cbAgua.addItem(new Tripla ("", null, "Indiferente"));           
        cbAgua.addItem(new Tripla (" AND agua_inmueble ", null, "Si"));   
        cbAgua.addItem(new Tripla (" AND NOT agua_inmueble ", null, "No")); 
        
        cbTelefonia.removeAllItems();
        cbTelefonia.addItem(new Tripla ("", null, "Indiferente"));           
        cbTelefonia.addItem(new Tripla (" AND telefono_inmueble ", null, "Si"));   
        cbTelefonia.addItem(new Tripla (" AND NOT telefono_inmueble ", null, "No")); 
        
        cbPavimento.removeAllItems();
        cbPavimento.addItem(new Tripla ("", null, "Indiferente"));           
        cbPavimento.addItem(new Tripla (" AND pavimento_inmueble ", null, "Si"));   
        cbPavimento.addItem(new Tripla (" AND NOT pavimento_inmueble ", null, "No")); 

        cbCloaca.removeAllItems();
        cbCloaca.addItem(new Tripla ("", null, "Indiferente"));           
        cbCloaca.addItem(new Tripla (" AND cloaca_inmueble ", null, "Si"));   
        cbCloaca.addItem(new Tripla (" AND NOT cloaca_inmueble ", null, "No")); 
        
        cbGas.removeAllItems();
        cbGas.addItem(new Tripla ("", null, "Indiferente"));           
        cbGas.addItem(new Tripla (" AND gas_inmueble ", null, "Si"));   
        cbGas.addItem(new Tripla (" AND NOT gas_inmueble ", null, "No")); 
        
        cbEstado.removeAllItems();
        cbEstado.addItem(new Tripla (" AND estado_inmueble = Alquiler ", null, "Alquiler"));           
        cbEstado.addItem(new Tripla (" AND estado_inmueble = Venta ", null, "Venta"));                      
         
    
        
        cbSector.removeAllItems();
        String consulta = "SELECT id_sector,nombre_sector FROM inmobiliaria.sector;";
        ResultSet rs = SqlMetodo.runQuery(consulta);
        try {
            cbSector.addItem(new Objetos.Tripla(0, null , "Indiferente"));
            while (rs.next())
                cbSector.addItem(new Objetos.Tripla(rs.getObject(1), null , rs.getObject(2)));
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error generando pantalla de búsqueda");
            Datos.Procedimientos.escribirEnLog("Error en BusquedaAVanzada - llenarCBGenerales: "+ex.getMessage());
        }
    } 
    
