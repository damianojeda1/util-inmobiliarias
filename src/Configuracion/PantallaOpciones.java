                if (f.exists())                
                    ubic = "C:/Program Files/PostgreSQL/9.4/bin/pg_dump";
                else
                    ubic = "C:/Program Files(x86)/PostgreSQL/9.4/bin/pg_dump";
                System.out.println(ubic);
                ProcessBuilder pb = new ProcessBuilder(ubic, "-i", "-h", "localhost", "-p", "8845", "-U",
                        "postgres", "-F", "c", "-b", "-v", "-f", "\""+path+fecha+".backup\"", "inmobiliaria");
                pb.environment().put("PGPASSWORD", "che14628");
                pb.redirectErrorStream(true);
