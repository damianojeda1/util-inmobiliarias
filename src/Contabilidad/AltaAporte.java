    private boolean controlesOk(){
        if (this.tfDescripcion.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Ingrese una descripción del aporte");
            this.tfDescripcion.grabFocus();
            return false;
        }
        if (this.tfResponsable.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Ingrese el responsable del aporte");
            this.tfResponsable.grabFocus();
            return false;
        }        
        if (!Datos.Procedimientos.isNumber(this.tfPrecio.getText())){
            JOptionPane.showMessageDialog(this, "Ingrese un valor válido");
            this.tfPrecio.setText("");
            this.tfPrecio.grabFocus();
            return false;
        }else{
            if (Float.parseFloat(this.tfPrecio.getText()) <= 0.0f){
                JOptionPane.showMessageDialog(this, "Ingrese un valor mayor a cero");
                this.tfPrecio.setText("");
                this.tfPrecio.grabFocus();
                return false;
            }
        }            
        return true;
    }

