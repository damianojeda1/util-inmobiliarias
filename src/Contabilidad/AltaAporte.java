    private void altaAporte(){
        String sql="INSERT INTO inmobiliaria.movimiento(\n" +
                    "descripcion_movimiento, tipo_movimiento, persona_movimiento, \n" +
                    "monto_movimiento, id_usuario_movimiento)\n" +
                    "VALUES ( 'Aporte - "+tfDescripcion.getText()+"', 'Ingreso', '"+tfResponsable.getText()+"', \n" +
                    tfPrecio.getText()+" , "+Datos.Macros.getID_USUARIO()+");";
        ProcedimientosSQL.SqlMetodo.runQuery(sql);
        Datos.Instancias.getInstance().pantallaPrincipal.llenarTablasCaja();
    }
