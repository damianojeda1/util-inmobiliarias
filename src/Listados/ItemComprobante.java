    public void mostrar(Integer id){
        limpiar();
        listar(id);
        setVisible(true);
    }
    private void listar( Integer id){
        String sql= "Select fecha_item, descripcion_item, monto_item from inmobiliaria.item where id_comprobantealquiler_item ="+id;
        ResultSet rs = SqlMetodo.runQuery(sql);
        int i=0;
        DefaultTableModel modelo= (DefaultTableModel)tblItem.getModel();
        try {
            while(rs.next()){
                modelo.setNumRows(i+1);
                tblItem.setModel(modelo);
                tblItem.setValueAt(rs.getObject("fecha_item"), i, 0);
                tblItem.setValueAt(rs.getObject("descripcion_item"), i, 1);
                tblItem.setValueAt(rs.getObject("monto_item"), i, 2);
                i++;
            }
        } catch (SQLException ex) {
            Datos.Procedimientos.escribirEnLog("Error en linea 50 en listar de la ItemComprobante: "+ex.toString());
        }
        
    }
    private void limpiar(){
        DefaultTableModel modelo= (DefaultTableModel)tblItem.getModel();
        modelo.setRowCount(0);
        tblItem.setModel(modelo);
    }
